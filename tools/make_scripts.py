"""Makes common\\ScriptData.h from the WorldVoice NVDA add-on's language detection and number rules, so the SAPI 5
voice splits text exactly as WorldVoice does:

    python tools\\make_scripts.py "<WorldVoice add-on>\\synthDrivers\\WorldVoice"  [output, default common\\ScriptData.h]

(The add-on: https://github.com/tsengwoody/WorldVoice; common\\ScriptData.h in the project was made from version 7.0.)

From the add-on: unicodeScripts\\script_data.py (the Unicode script of every character, Unicode 18) and
languageDetection\\scriptLanguages.py (which languages each script can be: SCRIPT_LANGUAGES, and the scripts whose
language the user chooses: DETECTION_SCRIPTS). From Python itself, which should be the version NVDA runs the add-on
on: str.isdecimal() (a digit, \\d in the add-on's regular expressions), str.isspace(), \\w (a word character, which
makes a sign before a number a hyphen) and the Latin-1 punctuation and symbols a number may hold between its digits
(the add-on's numbers.SYMBOLS).
"""
import os, re, sys, unicodedata


def ranges(test):
    out, start = [], None
    for cp in range(0x110000):
        ok = not (0xD800 <= cp <= 0xDFFF) and test(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    src_dir = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "common", "ScriptData.h")
    data = {}
    exec(open(os.path.join(src_dir, "unicodeScripts", "script_data.py"), encoding="utf-8").read(), data)
    lang = {"__name__": "scriptLanguages"}
    exec(open(os.path.join(src_dir, "languageDetection", "scriptLanguages.py"), encoding="utf-8").read(), lang)

    names = [""] + sorted({s for _a, _b, s in data["SCRIPT_RANGES"]})
    index = {n: i for i, n in enumerate(names)}
    lines = [
        "// ScriptData.h - generated by tools\\make_scripts.py from the WorldVoice NVDA add-on's language detection",
        f"// (Unicode {data['UNICODE_VERSION']}) and Python {sys.version.split()[0]}'s str.isdecimal() / str.isspace() / \\w (Unicode",
        f"// {unicodedata.unidata_version}). Do not edit; run make_scripts.py again.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace wv {",
        "",
        "// Script names; 0 is a character no script covers (WorldVoice's None).",
        "static const char* const kScriptNames[] = {",
    ]
    lines += [f'    "{n}",' for n in names]
    lines += ["};", "", "struct CodeRange { uint32_t first, last; uint16_t value; };", "",
              "// The script of each range of characters, sorted.", "static const CodeRange kScriptRanges[] = {"]
    row = []
    for a, b, s in data["SCRIPT_RANGES"]:
        row.append(f"{{0x{a:X},0x{b:X},{index[s]}}}")
        if len(row) == 8:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines += ["};", ""]
    word = re.compile(r"\w")
    tables = (
        ("kDigits", str.isdigit, "Python's str.isdigit() is true"),
        ("kDecimals", str.isdecimal, "Python's str.isdecimal() is true (\\d)"),
        ("kSpaces", str.isspace, "Python's str.isspace() is true"),
        ("kWordChars", lambda c: bool(word.match(c)), "\\w matches in Python (a word character)"),
        ("kNumberSymbols", lambda c: ord(c) < 0x100 and unicodedata.category(c)[0] in "PS",
         "a number may hold between its digits: Latin-1 punctuation and symbols (numbers.SYMBOLS)"),
    )
    for name, test, what in tables:
        lines.append(f"// Characters {what}.")
        lines.append(f"static const CodeRange {name}[] = {{")
        lines += [f"    {{0x{a:X},0x{b:X},1}}," for a, b in ranges(test)]
        lines += ["};", ""]
    lines += ["// The languages each script can be, in WorldVoice's order (SCRIPT_LANGUAGES), space separated.",
              "struct ScriptLanguages { const char* script; const char* languages; };",
              "static const ScriptLanguages kScriptLanguages[] = {"]
    for script, langs in lang["SCRIPT_LANGUAGES"].items():
        lines.append(f'    {{ "{script}", "{" ".join(langs)}" }},')
    lines += ["};", "",
              "// The scripts whose language the user chooses (DETECTION_SCRIPTS), with WorldVoice's setting name and default.",
              "struct ScriptSetting { const char* script; const char* setting; const char* language; };",
              "static const ScriptSetting kScriptSettings[] = {"]
    for row in lang["DETECTION_SCRIPTS"]:
        lines.append(f'    {{ "{row.script}", "{row.config_key}", "{row.default_language}" }},')
    lines += ["};", "", "}  // namespace wv", ""]
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(data['SCRIPT_RANGES'])} script ranges, {len(names) - 1} scripts, {len(lang['SCRIPT_LANGUAGES'])} script language lists, "
          f"Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}) -> {out_path}")


if __name__ == "__main__":
    main()
