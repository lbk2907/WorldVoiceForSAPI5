"""Makes common\\ScriptData.h from the WorldVoice NVDA add-on's language detection, so the SAPI 5 voice splits text
exactly as WorldVoice does:

    python tools\\make_scripts.py "<WorldVoice add-on>\\synthDrivers\\WorldVoice\\languageDetection"  [output, default common\\ScriptData.h]

(The add-on: https://github.com/tsengwoody/WorldVoice; common\\ScriptData.h in the project was made from version 6.2.)

From the add-on: script_data.py (the Unicode script of every character, Unicode 16) and __init__.py (which
languages each script can be: SCRIPT_LANGUAGES, and the scripts whose language the user chooses: SCRIPT_CONFIG_KEYS).
From Python itself: str.isdigit() and str.isspace(), which WorldVoice uses for numbers and, when spelling, spaces,
and str.isdecimal(), the digits its punctuation pauses look for (\\d in a regular expression).
"""
import os, re, sys


def ranges(test):
    out, start = [], None
    for cp in range(0x110000):
        ok = not (0xD800 <= cp <= 0xDFFF) and test(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def main():
    src_dir = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "common", "ScriptData.h")
    data = {}
    exec(open(os.path.join(src_dir, "script_data.py"), encoding="utf-8").read(), data)
    init = open(os.path.join(src_dir, "__init__.py"), encoding="utf-8").read()
    lang = {}
    start = init.index("BASIC_LATIN = (")
    end = init.index("\n\n\ndef ", start)
    exec(init[start:end], lang)          # the language tuples, SCRIPT_LANGUAGES and SCRIPT_CONFIG_KEYS

    names = [""] + sorted({s for _a, _b, s in data["SCRIPT_RANGES"]})
    index = {n: i for i, n in enumerate(names)}
    lines = [
        "// ScriptData.h - generated by tools\\make_scripts.py from the WorldVoice NVDA add-on's language detection",
        f"// (Unicode {data['UNICODE_VERSION']}) and Python's str.isdigit() / str.isdecimal() / str.isspace(). Do not edit; run make_scripts.py again.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace wv {",
        "",
        "// Script names; 0 is a character no script covers (WorldVoice's None).",
        "static const char* const kScriptNames[] = {",
    ]
    lines += [f'    "{n}",' for n in names]
    lines += ["};", "", "struct CodeRange { uint32_t first, last; uint16_t value; };", "",
              "// The script of each range of characters, sorted.", "static const CodeRange kScriptRanges[] = {"]
    row = []
    for a, b, s in data["SCRIPT_RANGES"]:
        row.append(f"{{0x{a:X},0x{b:X},{index[s]}}}")
        if len(row) == 8:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines += ["};", ""]
    for name, test, what in (("kDigits", str.isdigit, "str.isdigit()"), ("kDecimals", str.isdecimal, "str.isdecimal()"),
                             ("kSpaces", str.isspace, "str.isspace()")):
        lines.append(f"// Characters for which Python's {what} is true.")
        lines.append(f"static const CodeRange {name}[] = {{")
        lines += [f"    {{0x{a:X},0x{b:X},1}}," for a, b in ranges(test)]
        lines += ["};", ""]
    lines += ["// The languages each script can be, in WorldVoice's order (SCRIPT_LANGUAGES), space separated.",
              "struct ScriptLanguages { const char* script; const char* languages; };",
              "static const ScriptLanguages kScriptLanguages[] = {"]
    for script, langs in lang["SCRIPT_LANGUAGES"].items():
        lines.append(f'    {{ "{script}", "{" ".join(langs)}" }},')
    lines += ["};", "",
              "// The scripts whose language the user chooses (SCRIPT_CONFIG_KEYS), with WorldVoice's setting name.",
              "struct ScriptSetting { const char* script; const char* setting; };",
              "static const ScriptSetting kScriptSettings[] = {"]
    for script, key in lang["SCRIPT_CONFIG_KEYS"].items():
        lines.append(f'    {{ "{script}", "{key}" }},')
    lines += ["};", "", "}  // namespace wv", ""]
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{len(data['SCRIPT_RANGES'])} script ranges, {len(names) - 1} scripts, {len(lang['SCRIPT_LANGUAGES'])} script language lists -> {out_path}")


if __name__ == "__main__":
    main()
